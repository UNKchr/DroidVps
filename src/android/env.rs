use std::env;
use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use nix::unistd::Uid;
use crate::error::DroidError;

/// Ruta estándar de binarios en el entorno Termux de Android
pub const TERMUX_BIN_DIR: &str = "/data/data/com.termux/files/usr/bin";

/// Ruta estándar de scripts post-fs-data / late_start en Magisk, KernelSU y APatch
pub const ADB_SERVICE_D_DIR: &str = "/data/adb/service.d";

/// Nombre del script de auto-arranque en el inicio de Android
pub const BOOT_SCRIPT_NAME: &str = "99_droidvps_autostart.sh";

/// Ruta de instalación canónica del binario estático en Android
pub const DEFAULT_INSTALL_BIN_PATH: &str = "/data/local/droidvps/bin/droidvps";

/// Verifica que el proceso actual se esté ejecutando con privilegios de superusuario (`UID == 0`).
pub fn ensure_root_privileges() -> Result<(), DroidError> {
    if !Uid::effective().is_root() {
        return Err(DroidError::Android(
            "Root privileges required (UID 0). Run with 'su -mm -c \"droidvps ...\"' or install the Termux wrapper.".into(),
        ));
    }
    Ok(())
}

/// Instala el binario actual en `/data/local/droidvps/bin/droidvps` y configura los wrappers
/// `droidvps` y `dvps` en el `PATH` de Termux (`/data/data/com.termux/files/usr/bin`) si Termux está presente.
pub fn setup_standalone_environment(custom_termux_bin: Option<&Path>) -> Result<PathBuf, DroidError> {
    let current_exe = env::current_exe()?;
    let target_bin = PathBuf::from(DEFAULT_INSTALL_BIN_PATH);

    if let Some(parent) = target_bin.parent() {
        if !parent.exists() {
            fs::create_dir_all(parent)?;
        }
    }

    // Copiar el binario a la ruta permanente si se está ejecutando desde otra ubicación (ej. /data/local/tmp)
    if current_exe != target_bin {
        fs::copy(&current_exe, &target_bin)?;
        fs::set_permissions(&target_bin, fs::Permissions::from_mode(0o755))?;
    }

    // Crear enlace simbólico `dvps` junto al binario principal
    if let Some(parent) = target_bin.parent() {
        let dvps_bin = parent.join("dvps");
        if dvps_bin.exists() {
            let _ = fs::remove_file(&dvps_bin);
        }
        let _ = std::os::unix::fs::symlink(&target_bin, &dvps_bin);
    }

    // Si el directorio de binarios de Termux existe, instalar wrappers con elevación automática `su -mm`
    let termux_bin = custom_termux_bin.unwrap_or_else(|| Path::new(TERMUX_BIN_DIR));
    if termux_bin.exists() {
        install_termux_wrappers_in(termux_bin, &target_bin)?;
    }

    Ok(target_bin)
}

/// Genera los scripts puente `droidvps` y `dvps` dentro del directorio `bin` de Termux.
/// Se utiliza `\x24` para representar el carácter ASCII `$` sin ambigüedades de escape.
pub fn install_termux_wrappers_in(termux_bin_dir: &Path, target_bin: &Path) -> Result<(), DroidError> {
    if !termux_bin_dir.exists() {
        return Err(DroidError::Android(format!(
            "Termux binary directory not found at '{}'",
            termux_bin_dir.display()
        )));
    }

    let wrapper_content = format!(
        "#!/system/bin/sh\n\
         # Auto-generated by droidvps for seamless Termux execution\n\
         if [ \"\x24(id -u)\" = \"0\" ]; then\n\
             exec \"{bin}\" \"\x24@\"\n\
         else\n\
             exec su -mm -c \"{bin} \x24*\"\n\
         fi\n",
        bin = target_bin.display()
    );

    for name in ["droidvps", "dvps"] {
        let wrapper_path = termux_bin_dir.join(name);
        fs::write(&wrapper_path, &wrapper_content)?;
        fs::set_permissions(&wrapper_path, fs::Permissions::from_mode(0o755))?;
    }

    Ok(())
}

/// Configura un script de inicio automático en `/data/adb/service.d/` (Magisk / KernelSU / APatch)
/// para levantar el nodo VPS automáticamente cuando el dispositivo Android enciende.
pub fn configure_boot_autostart(
    rootfs: &Path,
    service_d_override: Option<&Path>,
) -> Result<PathBuf, DroidError> {
    let service_dir = service_d_override.unwrap_or_else(|| Path::new(ADB_SERVICE_D_DIR));
    if !service_dir.exists() {
        fs::create_dir_all(service_dir)?;
    }

    let script_path = service_dir.join(BOOT_SCRIPT_NAME);
    let script_content = format!(
        "#!/system/bin/sh\n\
         # Auto-generated by droidvps - Headless VPS Boot Service\n\
         while [ \"\x24(getprop sys.boot_completed)\" != \"1\" ]; do\n\
             sleep 2\n\
         done\n\
         sleep 5\n\
         \"{bin}\" start --target \"{rootfs}\" >/data/local/droidvps/boot.log 2>&1\n",
        bin = DEFAULT_INSTALL_BIN_PATH,
        rootfs = rootfs.display()
    );

    fs::write(&script_path, script_content)?;
    fs::set_permissions(&script_path, fs::Permissions::from_mode(0o755))?;

    Ok(script_path)
}

/// Elimina el script de auto-arranque en `/data/adb/service.d/` si existe
pub fn remove_boot_autostart(service_d_override: Option<&Path>) -> Result<bool, DroidError> {
    let service_dir = service_d_override.unwrap_or_else(|| Path::new(ADB_SERVICE_D_DIR));
    let script_path = service_dir.join(BOOT_SCRIPT_NAME);

    if script_path.exists() {
        fs::remove_file(script_path)?;
        Ok(true)
    } else {
        Ok(false)
    }
}

/// Devuelve `true` si el auto-arranque en el boot de Android está habilitado
pub fn is_boot_autostart_enabled(service_d_override: Option<&Path>) -> bool {
    let service_dir = service_d_override.unwrap_or_else(|| Path::new(ADB_SERVICE_D_DIR));
    service_dir.join(BOOT_SCRIPT_NAME).exists()
}