pub mod download;
pub mod extract;

use std::fs;
use std::path::Path;
use crate::error::DroidError;
use crate::rootfs::download::download_and_verify;
use crate::rootfs::extract::extract_tarball;

/// Ruta por defecto dentro de la partición `/data` de Android para alojar el contenedor
pub const DEFAULT_ROOTFS_PATH: &str = "/data/local/droidvps/rootfs";

/// URL oficial de Alpine Linux Minimal (v3.19.1) para arquitectura ARM64 (`aarch64`)
pub const ALPINE_URL: &str = "https://dl-cdn.alpinelinux.org/alpine/v3.19/releases/aarch64/alpine-minirootfs-3.19.1-aarch64.tar.gz";

/// Hash criptográfico SHA256 oficial correspondiente al tarball de Alpine v3.19.1 aarch64
pub const ALPINE_SHA256: &str = "7ef5eef3a5b1d198dfb1610cde1ef5b0755ff5d838fb1e5e1b9f42b59214820f";

/// Verifica si el entorno rootfs está inicializado usando `symlink_metadata` (`lstat`)
/// para no fallar con enlaces simbólicos absolutos (`/bin/sh -> /bin/busybox`) fuera del chroot.
pub fn is_rootfs_initialized(target_dir: &Path) -> bool {
    target_dir.join("bin/sh").symlink_metadata().is_ok()
        && target_dir.join("etc/alpine-release").symlink_metadata().is_ok()
}

/// Orquesta la descarga, verificación criptográfica, extracción y configuración base del rootfs
pub fn setup_rootfs(target_dir: &Path) -> Result<(), DroidError> {
    if is_rootfs_initialized(target_dir) {
        println!(
            "[*] Rootfs environment is already initialized at: {}",
            target_dir.display()
        );
        configure_network_files(target_dir)?;
        configure_android_groups(target_dir)?;
        return Ok(());
    }

    if !target_dir.exists() {
        fs::create_dir_all(target_dir)?;
    }

    let temp_tarball = target_dir.join("alpine-minirootfs.tar.gz");

    println!("[*] Downloading Alpine Linux Minimal (aarch64)...");
    download_and_verify(ALPINE_URL, ALPINE_SHA256, &temp_tarball)?;

    println!("[*] Extracting filesystem while preserving POSIX permissions...");
    let extract_result = extract_tarball(&temp_tarball, target_dir);

    if temp_tarball.exists() {
        let _ = fs::remove_file(&temp_tarball);
    }
    extract_result?;

    println!("[*] Configuring DNS resolution (/etc/resolv.conf) and /etc/hosts...");
    configure_network_files(target_dir)?;

    println!("[*] Registering Android kernel network groups (AID_INET / AID_NET_RAW) in /etc/group...");
    configure_android_groups(target_dir)?;

    Ok(())
}

/// Configura `/etc/resolv.conf` y `/etc/hosts` dentro del rootfs para habilitar resolución DNS
fn configure_network_files(target_dir: &Path) -> Result<(), DroidError> {
    let etc_dir = target_dir.join("etc");
    if !etc_dir.exists() {
        fs::create_dir_all(&etc_dir)?;
    }

    let resolv_path = etc_dir.join("resolv.conf");
    let resolv_content = "# Auto-generated by droidvps\n\
                          nameserver 1.1.1.1\n\
                          nameserver 8.8.8.8\n\
                          nameserver 9.9.9.9\n";
    fs::write(resolv_path, resolv_content)?;

    let hosts_path = etc_dir.join("hosts");
    if !hosts_path.exists() {
        let hosts_content = "127.0.0.1\tlocalhost droidvps\n\
                             ::1\t\tlocalhost ip6-localhost ip6-loopback\n";
        fs::write(hosts_path, hosts_content)?;
    }

    Ok(())
}

/// Registra de forma preventiva los grupos suplementarios del kernel Android en `<rootfs>/etc/group`:
/// - `aid_inet` (GID 3003): Creación de sockets AF_INET / AF_INET6
/// - `aid_net_raw` (GID 3004): Creación de sockets ICMP / SOCK_RAW (ping)
pub fn configure_android_groups(target_dir: &Path) -> Result<(), DroidError> {
    let group_path = target_dir.join("etc/group");
    if !group_path.exists() {
        return Ok(());
    }

    let mut content = fs::read_to_string(&group_path)?;
    let mut modified = false;

    if !content.contains(":3003:") {
        if !content.ends_with('\n') {
            content.push('\n');
        }
        content.push_str("aid_inet:x:3003:root\n");
        modified = true;
    }

    if !content.contains(":3004:") {
        if !content.ends_with('\n') {
            content.push('\n');
        }
        content.push_str("aid_net_raw:x:3004:root\n");
        modified = true;
    }

    if modified {
        fs::write(&group_path, content)?;
    }

    Ok(())
}